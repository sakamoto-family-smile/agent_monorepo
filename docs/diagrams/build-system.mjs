// Build a system's architecture diagrams from its spec files.
//
//   node build-system.mjs <system-dir>
//   e.g. node build-system.mjs systems/driving-license-bot
//
// For each spec.<variant>.mjs in the directory it writes:
//   - <variant>.svg          static SVG (from lib/render.mjs)
//   - Diagram.<Variant>.tsx   thin React wrapper around the same spec + renderer
//
// PNGs are produced separately (see README) since they need a rasterizer.
import { readdirSync, writeFileSync } from "node:fs";
import { join, basename } from "node:path";
import { renderDiagram } from "./lib/render.mjs";

const dir = process.argv[2];
if (!dir) {
  console.error("usage: node build-system.mjs <system-dir>");
  process.exit(1);
}

const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const specFiles = readdirSync(dir).filter((f) => /^spec\.[a-z]+\.mjs$/.test(f));

for (const file of specFiles) {
  const variant = file.match(/^spec\.([a-z]+)\.mjs$/)[1];
  const { spec } = await import(join(process.cwd(), dir, file));
  const svg = renderDiagram(spec);
  writeFileSync(join(dir, `${variant}.svg`), svg + "\n");
  console.log(`wrote ${dir}/${variant}.svg`);
}

// One shared TSX component for all variants in the folder. The SVG is
// pre-rendered at build time and embedded as a trusted static string, so the
// component ships no Node-only deps (fs) to the browser.
const sysName = basename(dir);
const comp = cap(sysName.replace(/[-_](.)/g, (_, c) => c.toUpperCase())) + "Diagram";
const rendered = {};
for (const file of specFiles) {
  const variant = file.match(/^spec\.([a-z]+)\.mjs$/)[1];
  const { spec } = await import(join(process.cwd(), dir, file));
  rendered[variant] = { title: spec.title, svg: renderDiagram(spec) };
}
const variants = Object.keys(rendered);
const esc = (s) => s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
const tsx =
  `// AUTO-GENERATED by build-system.mjs — do not edit by hand.\n` +
  `// Embeds the build-time-rendered ${sysName} architecture SVG(s).\n` +
  `// Regenerate: node docs/diagrams/build-system.mjs ${dir}\n` +
  `const VARIANTS = {\n` +
  variants
    .map((v) => `  ${v}: { title: ${JSON.stringify(rendered[v].title)}, svg: \`${esc(rendered[v].svg)}\` },`)
    .join("\n") +
  `\n} as const;\n\n` +
  `export type ${comp}Variant = keyof typeof VARIANTS;\n\n` +
  `export default function ${comp}({ variant = "${variants[0]}" }: { variant?: ${comp}Variant }) {\n` +
  `  const v = VARIANTS[variant];\n` +
  `  return (\n` +
  `    <div\n` +
  `      role="img"\n` +
  `      aria-label={v.title}\n` +
  `      style={{ width: "100%" }}\n` +
  `      dangerouslySetInnerHTML={{ __html: v.svg }}\n` +
  `    />\n` +
  `  );\n` +
  `}\n`;
writeFileSync(join(dir, `${comp}.tsx`), tsx);
console.log(`wrote ${dir}/${comp}.tsx`);
