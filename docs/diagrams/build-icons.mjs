// build-icons.mjs
// ---------------------------------------------------------------------------
// Converts the official Google Cloud product SVGs in ./gcp-icons-src into a
// single, collision-free <symbol> sprite.
//
// Why this is needed: the official icons declare colors via internal
// `<style>.cls-N{fill:#..}</style>` blocks and share generic ids
// (`mask`, `Oval`, `Fill-2`, ...). Dropping several into one document would
// make those CSS classes and ids collide. This script inlines every fill as a
// presentation attribute, strips <defs>/<style>/<title>/ids, and wraps each
// icon as `<symbol id="gcp-<name>" viewBox="0 0 24 24">`.
//
// Outputs (committed, so the diagram builds without this script):
//   - gcpIconDefs.ts          → export const GCP_ICON_DEFS (for the TSX component)
//   - gcp-icon-defs.partial.svg → same markup (for render-preview.mjs)
//
// Re-run after changing the source set:  node build-icons.mjs
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, "gcp-icons-src");

/** Parse `<style>.cls-1{fill:#x;}</style>` into { cls-1: { fill, fillRule } }. */
function parseStyle(raw) {
  const map = {};
  const block = raw.match(/<style>([\s\S]*?)<\/style>/i)?.[1] ?? "";
  for (const rule of block.matchAll(/([^{}]+)\{([^}]*)\}/g)) {
    const [, selectors, body] = rule;
    const fill = body.match(/fill:\s*([^;}]+)/)?.[1]?.trim();
    const fillRule = body.match(/fill-rule:\s*([^;}]+)/)?.[1]?.trim();
    for (const sel of selectors.split(",")) {
      const s = sel.trim();
      if (!s.startsWith(".")) continue; // ignore filter/mask-only selectors
      const key = s.slice(1);
      map[key] = { ...map[key], ...(fill && { fill }), ...(fillRule && { fillRule }) };
    }
  }
  return map;
}

function toSymbol(name, raw) {
  const classMap = parseStyle(raw);
  let inner = raw
    .replace(/<\?xml[^>]*\?>/gi, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .match(/<svg[^>]*>([\s\S]*)<\/svg>/i)?.[1] ?? "";

  inner = inner
    .replace(/<defs>[\s\S]*?<\/defs>/gi, "") // styles, masks, filters
    .replace(/<title>[\s\S]*?<\/title>/gi, "")
    .replace(/\s(?:id|data-name)="[^"]*"/g, "") // strip ids → no cross-icon collision
    // class="cls-N" → inlined fill / fill-rule presentation attributes
    .replace(/\sclass="([^"]+)"/g, (_m, cls) => {
      const def = classMap[cls.trim().split(/\s+/)[0]];
      if (!def) return "";
      const attrs = [];
      if (def.fill) attrs.push(`fill="${def.fill}"`);
      if (def.fillRule) attrs.push(`fill-rule="${def.fillRule}"`);
      return attrs.length ? " " + attrs.join(" ") : "";
    })
    // drop now-dangling mask/filter refs (their defs were removed)
    .replace(/\s(?:mask|filter)="url\(#[^)]*\)"/g, "")
    .replace(/\s+/g, " ")
    .trim();

  return `<symbol id="gcp-${name}" viewBox="0 0 24 24">${inner}</symbol>`;
}

// A non-product "Users" glyph (entry point), drawn in the GCP palette.
const USERS = `<symbol id="gcp-users" viewBox="0 0 24 24">` +
  `<circle cx="9" cy="8" r="3.2" fill="#4285f4"/>` +
  `<path d="M3 19c0-3.3 2.7-5.5 6-5.5s6 2.2 6 5.5z" fill="#669df6"/>` +
  `<circle cx="16.5" cy="9" r="2.6" fill="#aecbfa"/>` +
  `<path d="M14 19c0-2.6 1.7-4.4 4.2-4.4S22 16.4 22 19z" fill="#aecbfa"/>` +
  `</symbol>`;

const files = readdirSync(SRC).filter((f) => f.endsWith(".svg")).sort();
const symbols = [USERS, ...files.map((f) => toSymbol(f.replace(/\.svg$/, ""), readFileSync(join(SRC, f), "utf8")))];
const defs = symbols.join("\n");

writeFileSync(join(HERE, "gcp-icon-defs.partial.svg"), defs + "\n");
writeFileSync(
  join(HERE, "gcpIconDefs.ts"),
  `// AUTO-GENERATED by build-icons.mjs — do not edit by hand.\n` +
    `// Inlined from official Google Cloud product icons (./gcp-icons-src).\n` +
    `export const GCP_ICON_DEFS = \`${defs.replace(/`/g, "\\`").replace(/\$\{/g, "\\${")}\`;\n`,
);

console.log(`wrote ${symbols.length} symbols → gcpIconDefs.ts, gcp-icon-defs.partial.svg`);
